/// How long Clipboard History keeps what you copy. Pinned entries never expire.
public enum ClipboardRetention: String, CaseIterable, Codable, Sendable {
    case day, week, month, threeMonths, sixMonths, year, forever

    public static let standard = ClipboardRetention.month

    /// "1 Day", "30 Days", "Forever".
    public var title: String {
        switch self {
        case .day: "1 Day"
        case .week: "7 Days"
        case .month: "30 Days"
        case .threeMonths: "90 Days"
        case .sixMonths: "6 Months"
        case .year: "1 Year"
        case .forever: "Forever"
        }
    }

    /// How long an unpinned entry lives after it was last copied; nil for forever.
    public var duration: TimeInterval? {
        let day = 86_400.0
        switch self {
        case .day: return day
        case .week: return 7 * day
        case .month: return 30 * day
        case .threeMonths: return 90 * day
        case .sixMonths: return 182 * day
        case .year: return 365 * day
        case .forever: return nil
        }
    }
}

/// Where an entry shows in Clipboard History: pinned ones first, then by when they were last copied.
public enum ClipboardDateSection: Int, CaseIterable, Comparable, Sendable {
    case pinned, today, yesterday, thisWeek, earlier

    public var title: String {
        switch self {
        case .pinned: "Pinned"
        case .today: "Today"
        case .yesterday: "Yesterday"
        case .thisWeek: "This Week"
        case .earlier: "Earlier"
        }
    }

    public static func < (a: Self, b: Self) -> Bool { a.rawValue < b.rawValue }
}

/// What a search of Clipboard History asks for: a kind ("image", "links") as its first word, then words to find.
public struct ClipboardSearch: Equatable, Sendable {
    public var kind: ClipboardEntry.Kind?
    /// The rest, normalized (`FuzzyMatch.normalize`); empty for "every entry of the kind".
    public var text: String

    /// The words that name a kind when they start the search.
    static let kindWords: [String: ClipboardEntry.Kind] = [
        "text": .text, "texts": .text,
        "link": .link, "links": .link, "url": .link, "urls": .link,
        "email": .email, "emails": .email,
        "color": .color, "colors": .color, "colour": .color, "colours": .color,
        "image": .image, "images": .image, "picture": .image, "pictures": .image,
        "file": .files, "files": .files,
    ]

    public init(kind: ClipboardEntry.Kind? = nil, text: String) {
        self.kind = kind
        self.text = text
    }

    /// "image cat" → images with "cat" in them (their recognized text); "links" → every link; "hello" → anything with it.
    public init(parsing query: String) {
        let normalized = FuzzyMatch.normalize(query)
        let first = normalized.prefix { $0 != " " }
        if let kind = Self.kindWords[String(first)] {
            self.kind = kind
            text = String(normalized.dropFirst(first.count)).trimmingCharacters(in: .whitespaces)
        } else {
            kind = nil
            text = normalized
        }
    }

    public var isEmpty: Bool { kind == nil && text.isEmpty }
}

/// Clipboard History's rules, apart from the pasteboard: what to skip, when two copies are the same, the order, what
/// expires, the sections, search, and the "2 min ago" times.
public enum ClipboardHistoryRules {
    /// The most entries kept; past it the oldest unpinned ones go.
    public static let maxEntries = 1000
    /// Images and texts bigger than this aren't recorded.
    public static let maxBytes = 20 * 1024 * 1024

    /// Pasteboard types that say "don't keep this": the nspasteboard.org markers password managers and other apps
    /// set on secrets and on data they put there only for a moment, and password managers' own types.
    public static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "de.petermaar.PasswordManager",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    /// Apps whose copies are never recorded unless you take them off the list: password managers and Keychain Access.
    public static let defaultIgnoredApps: [(bundleID: String, name: String)] = [
        ("com.1password.1password", "1Password"),
        ("com.agilebits.onepassword7", "1Password 7"),
        ("com.bitwarden.desktop", "Bitwarden"),
        ("com.apple.keychainaccess", "Keychain Access"),
        ("com.apple.Passwords", "Passwords"),
        ("com.lastpass.LastPass", "LastPass"),
        ("com.dashlane.dashlanephonefinal", "Dashlane"),
        ("com.dashlane.Dashlane", "Dashlane"),
    ]

    /// Whether a copy should be left out of the history: it carries a "don't keep" type, or the app in front is one
    /// you ignore.
    public static func shouldSkip(types: [String], sourceBundleID: String?, ignoredBundleIDs: Set<String>) -> Bool {
        if types.contains(where: skippedTypes.contains) { return true }
        if let sourceBundleID, ignoredBundleIDs.contains(sourceBundleID) { return true }
        return false
    }

    // MARK: Same content

    /// What makes two copies the same: the kind and a SHA-256 of the content (the text, the image's bytes, the paths).
    public static func fingerprint(kind: ClipboardEntry.Kind, text: String = "", data: Data? = nil,
                                   files: [String] = []) -> String {
        var content = Data(kind.rawValue.utf8)
        content.append(0)
        switch kind {
        case .image: content.append(data ?? Data())
        case .files: content.append(Data(files.joined(separator: "\n").utf8))
        default: content.append(Data(text.utf8))
        }
        return SHA256.hash(data: content).map { String(format: "%02x", $0) }.joined()
    }

    /// What recording `entry` did to the history.
    public struct Recorded: Equatable, Sendable {
        /// Newest first.
        public var entries: [ClipboardEntry]
        /// The id the copy is under: the new entry's, or the earlier entry's with the same content.
        public var id: String
        /// False when the same content was already there (it moved to the top and keeps its id, pin and files).
        public var isNew: Bool
    }

    /// The history after `entry` was copied: the same content again moves the earlier entry to the top (its pin, name
    /// and files stay; the copy count goes up); anything else goes on top as new.
    public static func record(_ entry: ClipboardEntry, into entries: [ClipboardEntry]) -> Recorded {
        var entries = entries
        if let index = entries.firstIndex(where: { $0.fingerprint == entry.fingerprint }) {
            var existing = entries.remove(at: index)
            existing.copied = max(existing.copied, entry.copied)
            existing.timesCopied += 1
            existing.sourceName = entry.sourceName ?? existing.sourceName
            existing.sourceBundleID = entry.sourceBundleID ?? existing.sourceBundleID
            entries.insert(existing, at: insertionIndex(for: existing.copied, in: entries))
            return Recorded(entries: entries, id: existing.id, isNew: false)
        }
        entries.insert(entry, at: insertionIndex(for: entry.copied, in: entries))
        return Recorded(entries: entries, id: entry.id, isNew: true)
    }

    /// Where an entry copied at `date` goes in a newest-first list.
    static func insertionIndex(for date: Date, in entries: [ClipboardEntry]) -> Int {
        entries.firstIndex { $0.copied <= date } ?? entries.count
    }

    /// The entry that was used again (pasted or copied from the history) moved to the top, as if copied at `date`.
    public static func touch(_ id: String, in entries: [ClipboardEntry], at date: Date) -> [ClipboardEntry] {
        var entries = entries
        guard let index = entries.firstIndex(where: { $0.id == id }) else { return entries }
        var entry = entries.remove(at: index)
        entry.copied = max(entry.copied, date)
        entries.insert(entry, at: insertionIndex(for: entry.copied, in: entries))
        return entries
    }

    // MARK: Expiry

    /// The history without what expired (unpinned entries last copied before the retention period) and without the
    /// oldest unpinned entries past `limit`. Pinned entries always stay.
    public static func pruned(_ entries: [ClipboardEntry], retention: ClipboardRetention, now: Date,
                              limit: Int = maxEntries) -> (kept: [ClipboardEntry], removed: [ClipboardEntry]) {
        var kept: [ClipboardEntry] = []
        var removed: [ClipboardEntry] = []
        let cutoff = retention.duration.map { now.addingTimeInterval(-$0) }
        for entry in entries {
            if !entry.pinned, let cutoff, entry.copied < cutoff {
                removed.append(entry)
            } else {
                kept.append(entry)
            }
        }
        var excess = kept.count - limit
        if excess > 0 {
            // The oldest unpinned ones go first: walk from the end of the newest-first list.
            for index in kept.indices.reversed() where excess > 0 && !kept[index].pinned {
                removed.append(kept.remove(at: index))
                excess -= 1
            }
        }
        return (kept, removed)
    }

    /// Delete All, or everything copied since `date`: the unpinned entries go, the pinned ones stay.
    public static func clearing(_ entries: [ClipboardEntry], since date: Date? = nil)
        -> (kept: [ClipboardEntry], removed: [ClipboardEntry]) {
        var kept: [ClipboardEntry] = []
        var removed: [ClipboardEntry] = []
        for entry in entries {
            if !entry.pinned, date.map({ entry.copied >= $0 }) ?? true {
                removed.append(entry)
            } else {
                kept.append(entry)
            }
        }
        return (kept, removed)
    }

    // MARK: Sections

    /// Pinned, Today, Yesterday, This Week (the calendar week), or Earlier.
    public static func section(of entry: ClipboardEntry, now: Date, calendar: Calendar = .current)
        -> ClipboardDateSection {
        if entry.pinned { return .pinned }
        if calendar.isDate(entry.copied, inSameDayAs: now) { return .today }
        if let yesterday = calendar.date(byAdding: .day, value: -1, to: now),
           calendar.isDate(entry.copied, inSameDayAs: yesterday) { return .yesterday }
        if entry.copied <= now, calendar.isDate(entry.copied, equalTo: now, toGranularity: .weekOfYear) {
            return .thisWeek
        }
        return .earlier
    }

    /// The entries in the order the list shows them: by section, newest first in each.
    public static func ordered(_ entries: [ClipboardEntry], now: Date, calendar: Calendar = .current)
        -> [(section: ClipboardDateSection, entries: [ClipboardEntry])] {
        var groups: [ClipboardDateSection: [ClipboardEntry]] = [:]
        for entry in entries.sorted(by: { $0.copied > $1.copied }) {
            groups[section(of: entry, now: now, calendar: calendar), default: []].append(entry)
        }
        return ClipboardDateSection.allCases.compactMap { section in
            groups[section].map { (section, $0) }
        }
    }

    // MARK: Search

    /// What a search looks through, normalized once per entry: its name, its text (or file names), and the text read
    /// from an image.
    public static func searchText(of entry: ClipboardEntry) -> String {
        var parts: [String] = []
        if let customTitle = entry.customTitle { parts.append(customTitle) }
        switch entry.kind {
        case .files: parts.append(entry.files.map { URL(fileURLWithPath: $0).lastPathComponent }.joined(separator: " "))
        case .image: break
        default: parts.append(entry.text)
        }
        if let recognizedText = entry.recognizedText { parts.append(recognizedText) }
        return FuzzyMatch.normalize(parts.joined(separator: " "))
    }

    /// Whether an entry is what the search asks for: of its kind, with every typed word in its text, or its title a
    /// close fuzzy match ("scrsht" for "Screenshot 2026…").
    public static func matches(_ entry: ClipboardEntry, searchText: String, search: ClipboardSearch) -> Bool {
        if let kind = search.kind, entry.kind != kind { return false }
        guard !search.text.isEmpty else { return true }
        let words = search.text.split(separator: " ")
        if words.allSatisfy({ searchText.contains($0) }) { return true }
        // Letters in order, but only in the title and only tight ones: a history is too long for loose matches.
        guard let score = FuzzyMatch.score(search.text, entry.title) else { return false }
        return score >= 0.4
    }

    // MARK: Times

    /// "Just now", "5 min ago", "3 h ago", "Yesterday", "4 days ago"; nil from a week on (the caller writes a date).
    public static func relativeTime(_ date: Date, now: Date, calendar: Calendar = .current) -> String? {
        let seconds = now.timeIntervalSince(date)
        if seconds < 60 { return "Just now" }
        if seconds < 3600 { return "\(Int(seconds / 60)) min ago" }
        if calendar.isDate(date, inSameDayAs: now) { return "\(Int(seconds / 3600)) h ago" }
        let days = calendar.dateComponents([.day], from: calendar.startOfDay(for: date),
                                           to: calendar.startOfDay(for: now)).day ?? 0
        if days == 1 { return "Yesterday" }
        if days < 7 { return "\(days) days ago" }
        return nil
    }
}

/// Paste Sequentially: each run pastes the next older entry, starting from the newest. A new copy, or a pause longer
/// than `timeout`, starts it over.
public struct ClipboardPasteSequence: Equatable, Sendable {
    public static let timeout: TimeInterval = 30

    /// The index the last run pasted; nil before the first or after a reset.
    public private(set) var index: Int?
    private var last: Date?
    /// The pasteboard's change count right after the last run wrote to it.
    private var changeCount: Int?

    public init() {}

    /// The index to paste now, out of `count` entries; nil when there's nothing (more) to paste. `changeCount` is the
    /// pasteboard's now: if someone copied since the last run, the sequence starts over.
    public mutating func next(count: Int, changeCount: Int, now: Date) -> Int? {
        let continues = index != nil && self.changeCount == changeCount
            && last.map { now.timeIntervalSince($0) <= Self.timeout } == true
        let next = continues ? index! + 1 : 0
        guard next < count else { return nil }
        index = next
        last = now
        return next
    }

    /// After the run wrote the entry: the pasteboard's change count that counts as "nobody copied since".
    public mutating func wrote(changeCount: Int) {
        self.changeCount = changeCount
    }

    public mutating func reset() {
        index = nil
        last = nil
        changeCount = nil
    }
}
